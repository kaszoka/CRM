    public function isLocal(?string $postalCode): bool
    {
        if (!$postalCode) {
            return false;
        }

        $distance = $this->calculateDistance($postalCode);
        if ($distance === null) {
            return false;
        }

        return $distance <= self::LOCAL_RADIUS_KM;
    }

    public function calculateDistance(?string $postalCode): ?float
    {
        if (!$postalCode) {
            return null;
        }

        $prefix = substr(str_replace('-', '', $postalCode), 0, 2);
        if (!isset(self::POSTAL_COORDS[$prefix])) {
            return null;
        }

        [$lat, $lng] = self::POSTAL_COORDS[$prefix];
        return $this->haversine(self::HOME_LAT, self::HOME_LNG, $lat, $lng);
    }

    private function haversine(float $lat1, float $lon1, float $lat2, float $lon2): float
    {
        $earthRadius = 6371;
        $dLat = deg2rad($lat2 - $lat1);
        $dLon = deg2rad($lon2 - $lon1);

        $a = sin($dLat / 2) ** 2
            + cos(deg2rad($lat1)) * cos(deg2rad($lat2)) * sin($dLon / 2) ** 2;

        return $earthRadius * 2 * atan2(sqrt($a), sqrt(1 - $a));
    }
